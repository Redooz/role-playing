import { routingContextSchema } from '@rp/routing-policy'
import { baseLanguageOfLocale, tryCanonicalizeLocale } from '@rp/shared'
import { z } from 'zod'

/**
 * Zod schemas for the English/French eval task workflow (M0 D5).
 *
 * Zod is the source of truth. The JSON Schemas committed under `evals/schemas/`
 * are generated from these definitions with `z.toJSONSchema`; a unit test fails
 * when the committed files drift. Types are inferred with `z.infer`, so nothing
 * in this module needs a hand-written interface.
 *
 * Layout contract (see `validate.ts` for the walker that enforces it):
 *
 * ```text
 * evals/tasks/<dataset>/<version>/<lang>/.../*.json   -> taskEntrySchema
 * evals/golden/<lang>/<version>/.../*.json               -> goldenEntrySchema
 * ```
 */

/** Languages with a calibration workflow. Adding one here is not enough: §4.4.10 requires a golden set too. */
export const LANGS = ['en', 'fr'] as const
/** CEFR bands used for stratification (§4.4.2). */
export const CEFR_BANDS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'] as const
/** Calibration data may guide changes; holdouts stay frozen (§4.6.6). */
export const SPLITS = ['calibration', 'holdout'] as const

export const langSchema = z.enum(LANGS)
export const cefrBandSchema = z.enum(CEFR_BANDS)
export const splitSchema = z.enum(SPLITS)

export type Lang = z.infer<typeof langSchema>
export type CefrBand = z.infer<typeof cefrBandSchema>
export type Split = z.infer<typeof splitSchema>

/**
 * Where an entry came from (§4.6.9).
 *
 * M0 ships synthetic data only (resolved decision O4). `recorded` entries may
 * only appear after the consented collection workflow exists; `consentScope` on
 * the entry records the permission that covers storage, annotation, and eval use.
 */
export const provenanceSchema = z
  .strictObject({
    source: z.enum(['synthetic', 'recorded']),
    note: z.string().min(1).optional(),
    collectedAt: z.iso.datetime({ offset: true }).optional(),
  })
  .superRefine((provenance, ctx) => {
    if (provenance.source === 'recorded' && provenance.collectedAt === undefined) {
      ctx.addIssue({
        code: 'custom',
        path: ['collectedAt'],
        message:
          'recorded provenance must state collectedAt so retention and deletion can be scoped',
      })
    }
  })

export type Provenance = z.infer<typeof provenanceSchema>

/**
 * Ordered transcript turns. `role: 'user'` is the learner, `role: 'persona'` is
 * one of the AI characters. Audio references arrive in a later milestone; M0 is
 * text-only.
 */
export const turnSchema = z.strictObject({
  role: z.enum(['user', 'persona']),
  text: z.string().min(1),
})

export const taskContentSchema = z.strictObject({
  scenarioBrief: z.string().min(1).optional(),
  /**
   * Recorded turns for a replay task. A session task stores no persona turns
   * (the model generates them), so the array may be empty; the task refinement
   * still requires at least one turn for `mode: 'replay'`.
   */
  turns: z.array(turnSchema),
})

/** How a task is executed. Existing v1 tasks omit this and default to replay. */
export const taskModeSchema = z.enum(['replay', 'session', 'routing'])

export const localeTagSchema = z
  .string()
  .min(2)
  .refine((value) => tryCanonicalizeLocale(value) !== undefined, {
    message: 'expected a canonical BCP 47 locale tag with an en or fr base language',
  })

/**
 * Session execution block (M2 D6).
 *
 * `recordedPersonaTurns` is a canned-regression fixture only. A live session
 * never reads it: persona turns come from the model. It is optional so a live
 * task cannot accidentally look deterministic.
 */
export const sessionTaskSchema = z.strictObject({
  personaId: z.string().min(1),
  /**
   * Personas eligible in this session, in driver order. The first entry is the
   * opening persona and must equal `personaId`. Omitted means the M2
   * single-persona mode.
   */
  personaIds: z.array(z.string().min(1)).min(1).max(3).optional(),
  personaVersion: z.string().min(1),
  scenarioId: z.string().min(1),
  scenarioVersion: z.string().min(1),
  /** Learner turns, in order. Persona turns are generated by the model. */
  scriptedUserTurns: z.array(z.string().min(1)).min(1),
  /** Canned regression only: one reply per persona turn, in order. */
  recordedPersonaTurns: z.array(z.string().min(1)).min(1).optional(),
})

export type SessionTask = z.infer<typeof sessionTaskSchema>

/**
 * Routing execution block (M3a D3).
 *
 * The context is exactly what a policy may see. Labels live only in golden
 * entries, never in this block, so a policy cannot accidentally read the answer.
 */
export const routingTaskSchema = z.strictObject({
  context: routingContextSchema,
})

export type RoutingTask = z.infer<typeof routingTaskSchema>

/** A name → version map, e.g. `{ rubric: 'v1', annotationGuideline: 'v1' }`. */
const annotationVersionsSchema = z
  .record(z.string().min(1), z.string().min(1))
  .refine((versions) => Object.keys(versions).length > 0, {
    message: 'annotationVersions must name at least one annotation artifact',
  })

export const taskEntrySchema = z
  .strictObject({
    /** Stable within one dataset version + language + locale. */
    id: z.string().min(1),
    lang: langSchema,
    /** Canonical BCP 47 locale. Defaults to the base language when absent. */
    locale: localeTagSchema.optional(),
    mode: taskModeSchema.default('replay'),
    domain: z.string().min(1),
    scenarioType: z.string().min(1),
    cefrBand: cefrBandSchema,
    /**
     * Who produced the learner side of the transcript. Calibration/holdout splits
     * are disjoint by this id, never by utterance (§4.6.5).
     */
    speakerId: z.string().min(1),
    split: splitSchema,
    provenance: provenanceSchema,
    /** Non-empty permission scope. Synthetic data uses `synthetic-no-consent-required`. */
    consentScope: z.string().min(1),
    annotationVersions: annotationVersionsSchema,
    content: taskContentSchema,
    /** Present exactly when `mode` is `session`. */
    session: sessionTaskSchema.optional(),
    /** Present exactly when `mode` is `routing`. */
    routing: routingTaskSchema.optional(),
  })
  .superRefine((task, ctx) => {
    if (task.locale !== undefined && baseLanguageOfLocale(task.locale) !== task.lang) {
      ctx.addIssue({
        code: 'custom',
        path: ['locale'],
        message: `locale "${task.locale}" does not match base language "${task.lang}"`,
      })
    }

    if (task.routing !== undefined && task.mode !== 'routing') {
      ctx.addIssue({
        code: 'custom',
        path: ['routing'],
        message: "only a routing task may carry a 'routing' block",
      })
    }

    if (task.mode === 'session') {
      if (task.session === undefined) {
        ctx.addIssue({
          code: 'custom',
          path: ['session'],
          message: "a session task requires a 'session' block",
        })
      }
      if (task.routing !== undefined) {
        ctx.addIssue({
          code: 'custom',
          path: ['routing'],
          message: 'a session task cannot carry routing context',
        })
      }
      if (task.content.turns.length > 0) {
        ctx.addIssue({
          code: 'custom',
          path: ['content', 'turns'],
          message: 'a session task must not store persona turns; the model generates them',
        })
      }
      if (task.session !== undefined) {
        const personaIds = task.session.personaIds
        if (personaIds !== undefined) {
          if (new Set(personaIds).size !== personaIds.length) {
            ctx.addIssue({
              code: 'custom',
              path: ['session', 'personaIds'],
              message: 'session personaIds must not repeat',
            })
          }
          if (personaIds[0] !== task.session.personaId) {
            ctx.addIssue({
              code: 'custom',
              path: ['session', 'personaIds'],
              message: 'the first session persona must be the opening personaId',
            })
          }
        }
      }
    } else if (task.mode === 'routing') {
      if (task.routing === undefined) {
        ctx.addIssue({
          code: 'custom',
          path: ['routing'],
          message: "a routing task requires a 'routing' block",
        })
      } else {
        if (task.routing.context.decisionId !== task.id) {
          ctx.addIssue({
            code: 'custom',
            path: ['routing', 'context', 'decisionId'],
            message: `routing decisionId must equal the task id "${task.id}"`,
          })
        }
        if (task.routing.context.lang !== task.lang) {
          ctx.addIssue({
            code: 'custom',
            path: ['routing', 'context', 'lang'],
            message: `routing context language "${task.routing.context.lang}" does not match task language "${task.lang}"`,
          })
        }
      }
      if (task.session !== undefined) {
        ctx.addIssue({
          code: 'custom',
          path: ['session'],
          message: 'a routing task cannot carry a session block',
        })
      }
      if (task.content.turns.length > 0) {
        ctx.addIssue({
          code: 'custom',
          path: ['content', 'turns'],
          message: 'a routing task stores its transcript in the routing context',
        })
      }
    } else {
      if (task.session !== undefined) {
        ctx.addIssue({
          code: 'custom',
          path: ['session'],
          message: "only a session task may carry a 'session' block",
        })
      }
      if (task.content.turns.length === 0) {
        ctx.addIssue({
          code: 'custom',
          path: ['content', 'turns'],
          message: 'a replay task requires at least one recorded turn',
        })
      }
    }
  })

export type TaskEntry = z.infer<typeof taskEntrySchema>

/**
 * Agreement block required before a golden entry may be `stable` (§4.4.4).
 *
 * `metric` names the statistic (for example `cohen_kappa`, `icc_2_1`, or
 * `percent_agreement`); `value` is its measured value. The rubric that defines
 * the required threshold is pre-registered per language (§4.4.6), not here.
 */
export const annotatorAgreementSchema = z.strictObject({
  /** At least two distinct annotators are needed for agreement to mean anything. */
  annotators: z.array(z.string().min(1)).min(1),
  metric: z.string().min(1),
  value: z.number().finite().min(-1).max(1),
  measuredAt: z.iso.datetime({ offset: true }).optional(),
  notes: z.string().min(1).optional(),
})

export type AnnotatorAgreement = z.infer<typeof annotatorAgreementSchema>

/**
 * True when agreement was measured by at least two distinct annotators and a
 * metric/value pair is stated. Agreement statistics live in [-1, 1].
 */
export function hasMeasuredAgreement(value: unknown): boolean {
  const parsed = annotatorAgreementSchema.safeParse(value)
  if (!parsed.success) return false
  return new Set(parsed.data.annotators).size >= 2 && parsed.data.metric.length > 0
}

/**
 * M3a acceptable-outcome labels.
 *
 * A label is a set, not one exact speaker. `allowUserYield` covers the valid
 * no-contribution case. The annotation source is explicit so an LLM pass can
 * never be mistaken for human ground truth.
 */
export const routingOutcomeLabelSchema = z
  .strictObject({
    intent: z.string().min(1),
    acceptablePersonaIds: z.array(z.string().min(1)),
    allowUserYield: z.boolean(),
    labelSource: z.enum(['agent', 'human']),
    note: z.string().min(1).optional(),
  })
  .superRefine((label, ctx) => {
    if (label.acceptablePersonaIds.length === 0 && !label.allowUserYield) {
      ctx.addIssue({
        code: 'custom',
        path: ['acceptablePersonaIds'],
        message: 'a routing label must accept at least one persona or learner yield',
      })
    }
    if (new Set(label.acceptablePersonaIds).size !== label.acceptablePersonaIds.length) {
      ctx.addIssue({
        code: 'custom',
        path: ['acceptablePersonaIds'],
        message: 'acceptablePersonaIds must not repeat',
      })
    }
  })

export type RoutingOutcomeLabel = z.infer<typeof routingOutcomeLabelSchema>

/**
 * One user turn's acceptable speakers in a session task.
 *
 * `turnIndex` is the index in `session.scriptedUserTurns`, not the transcript.
 * A label is a set: one persona, both personas in either order, or a learner
 * yield. Labels stay provisional until the annotation agreement gate.
 */
export const speakerLabelSchema = z
  .strictObject({
    turnIndex: z.int().nonnegative(),
    acceptablePersonaIds: z.array(z.string().min(1)),
    allowUserYield: z.boolean(),
    labelSource: z.enum(['agent', 'human']),
    note: z.string().min(1).optional(),
  })
  .superRefine((label, ctx) => {
    if (label.acceptablePersonaIds.length === 0 && !label.allowUserYield) {
      ctx.addIssue({
        code: 'custom',
        path: ['acceptablePersonaIds'],
        message: 'a speaker label must accept at least one persona or learner yield',
      })
    }
    if (new Set(label.acceptablePersonaIds).size !== label.acceptablePersonaIds.length) {
      ctx.addIssue({
        code: 'custom',
        path: ['acceptablePersonaIds'],
        message: 'acceptablePersonaIds must not repeat',
      })
    }
  })

export type SpeakerLabel = z.infer<typeof speakerLabelSchema>

/** One human judgment about a single transcript. */
export const goldenEntrySchema = z
  .strictObject({
    /** Stable within one language + version. */
    id: z.string().min(1),
    lang: langSchema,
    /** Canonical BCP 47 locale. Defaults to the base language when absent. */
    locale: localeTagSchema.optional(),
    split: splitSchema,
    /**
     * Link to a task in the same language and version. When present it must
     * resolve, and the golden entry's split must match the task's split.
     */
    taskId: z.string().min(1).optional(),
    /**
     * Optional machine-readable reference to one model trial. A task can run
     * several rounds, so `taskId` alone cannot identify the transcript a label
     * describes. When any of these is present, all three are required.
     */
    runId: z.string().min(1).optional(),
    round: z.number().int().min(0).optional(),
    /** The harness trial id, `${round}:${lang}:${taskId}`. */
    trialId: z.string().min(1).optional(),
    /**
     * Which character the turn should be routed to (§4.4.3). `intent` is a short
     * human label; the persona ids are tournament arms, not model versions.
     */
    routingLabels: z
      .strictObject({
        intent: z.string().min(1),
        expectedPersonaId: z.string().min(1),
        acceptablePersonaIds: z.array(z.string().min(1)).optional(),
        note: z.string().min(1).optional(),
      })
      .optional(),
    /** M3a routing-replay labels; mutually exclusive with legacy routingLabels. */
    routingOutcome: routingOutcomeLabelSchema.optional(),
    /**
     * M3b session labels: acceptable speakers after each scripted user turn.
     * Mutually exclusive with routing labels; the entry must carry one family.
     */
    speakerLabels: z.array(speakerLabelSchema).min(1).optional(),
    /**
     * 1–5 rubric scores keyed by dimension name. Keeping dimension names as data
     * lets a rubric version add a dimension without a schema major bump.
     */
    dimensionScores: z
      .record(
        z.string().min(1),
        z.strictObject({
          score: z.number().int().min(1).max(5),
          rationale: z.string().min(1).optional(),
        }),
      )
      .refine((scores) => Object.keys(scores).length > 0, {
        message: 'dimensionScores must contain at least one dimension',
      })
      .optional(),
    /** Spans that justify a score or label, by turn index and text reference. */
    evidenceSpans: z.array(
      z.strictObject({
        turnIndex: z.number().int().min(0),
        /** Quote (or stable fragment) from the referenced turn. */
        textRef: z.string().min(1),
        dimension: z.string().min(1).optional(),
        note: z.string().min(1).optional(),
      }),
    ),
    /** Blind pairwise comparisons, with presentation order recorded (§4.4.7). */
    pairwisePreferences: z.array(
      z.strictObject({
        opponentId: z.string().min(1),
        preference: z.enum(['self', 'opponent', 'tie']),
        presentationOrder: z.enum(['self-first', 'opponent-first']),
        blinded: z.boolean(),
        note: z.string().min(1).optional(),
      }),
    ),
    /** Optional until measured. A `stable` entry must carry a valid block. */
    annotatorAgreement: annotatorAgreementSchema.optional(),
    /**
     * `draft` entries are usable for tooling checks but are not ground truth.
     * `stable` is reserved for entries whose labels passed the agreement gate.
     */
    status: z.enum(['draft', 'stable', 'retired']),
    notes: z.string().min(1).optional(),
  })
  .superRefine((entry, ctx) => {
    const trialFields = [entry.runId, entry.round, entry.trialId]
    const present = trialFields.filter((value) => value !== undefined).length
    if (present > 0 && present < trialFields.length) {
      ctx.addIssue({
        code: 'custom',
        path: ['trialId'],
        message: 'runId, round and trialId must be supplied together',
      })
    }
    if (entry.trialId !== undefined && entry.round !== undefined && entry.taskId !== undefined) {
      const expected = `${entry.round}:${entry.lang}:${entry.taskId}`
      if (entry.trialId !== expected) {
        ctx.addIssue({
          code: 'custom',
          path: ['trialId'],
          message: `trialId must match "${expected}"`,
        })
      }
    }

    if (
      entry.routingLabels === undefined &&
      entry.routingOutcome === undefined &&
      entry.speakerLabels === undefined
    ) {
      ctx.addIssue({
        code: 'custom',
        path: ['routingLabels'],
        message: 'a golden entry requires routingLabels, routingOutcome or speakerLabels',
      })
    }
    if (entry.routingLabels !== undefined && entry.routingOutcome !== undefined) {
      ctx.addIssue({
        code: 'custom',
        path: ['routingOutcome'],
        message: 'routingLabels and routingOutcome are mutually exclusive',
      })
    }
    if (
      entry.speakerLabels !== undefined &&
      (entry.routingLabels !== undefined || entry.routingOutcome !== undefined)
    ) {
      ctx.addIssue({
        code: 'custom',
        path: ['speakerLabels'],
        message: 'speakerLabels cannot be combined with routing labels',
      })
    }
    if (entry.speakerLabels !== undefined) {
      const turns = entry.speakerLabels.map((label) => label.turnIndex)
      for (const [index, turnIndex] of turns.entries()) {
        if (index === 0 && turnIndex !== 0) {
          ctx.addIssue({
            code: 'custom',
            path: ['speakerLabels', 0, 'turnIndex'],
            message: 'speakerLabels must start at the first user turn (index 0)',
          })
        } else if (index > 0 && turnIndex !== (turns[index - 1] ?? -1) + 1) {
          ctx.addIssue({
            code: 'custom',
            path: ['speakerLabels', index, 'turnIndex'],
            message: 'speakerLabels must cover consecutive user turns in order',
          })
        }
      }
    }
    if (entry.routingLabels !== undefined && entry.dimensionScores === undefined) {
      ctx.addIssue({
        code: 'custom',
        path: ['dimensionScores'],
        message: 'a legacy routingLabels entry requires dimensionScores',
      })
    }

    if (entry.status !== 'stable') return
    if (entry.routingOutcome?.labelSource === 'agent') {
      ctx.addIssue({
        code: 'custom',
        path: ['routingOutcome', 'labelSource'],
        message:
          "agent routing labels cannot be 'stable'; only blind human double-labelling can be stable",
      })
    }
    if (entry.speakerLabels?.some((label) => label.labelSource === 'agent')) {
      ctx.addIssue({
        code: 'custom',
        path: ['speakerLabels'],
        message:
          "agent speaker labels cannot be 'stable'; only blind human double-labelling can be stable",
      })
    }
    if (!hasMeasuredAgreement(entry.annotatorAgreement)) {
      ctx.addIssue({
        code: 'custom',
        path: ['annotatorAgreement'],
        message:
          "status 'stable' requires a measured annotatorAgreement block with at least 2 distinct annotators, a metric, and a value",
      })
    }
  })

export type GoldenEntry = z.infer<typeof goldenEntrySchema>
